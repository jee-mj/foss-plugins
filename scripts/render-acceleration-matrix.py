#!/usr/bin/env python3
"""Render schema-2 catalog evidence offline, or check freshness without writes."""

import argparse
from collections import Counter
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from lib.catalog_acceleration import validation_errors


def cell(value):
    """Keep catalog prose inside a single Markdown table cell."""
    return str(value).replace("|", "&#124;").replace("\n", " ").replace("\r", " ")


def attribute(value, *, local=False):
    if value is None:
        return "`null`"
    if local and not value.startswith("packages."):
        value = "packages.x86_64-linux." + value
    return "`" + cell(value) + "`"


def evidence_lines(evidence):
    lines = []
    for item in evidence:
        reference = item["reference"]
        target = reference if reference.startswith("https://") else "../" + reference
        lines.append(f"- [{cell(item['kind'])}: {cell(item['stage'])}]({target}) — "
                     f"{cell(item['summary'])} (revision: {attribute(item['revision'])}).")
    return lines


def render(catalog, identities):
    entries = catalog["entries"]
    actual = [(entry["id"], entry["repository"]) for entry in entries]
    if actual != list(identities.items()):
        raise ValueError("canonical identity/order mismatch against identity fixture")
    if catalog.get("schema_version") != 2:
        raise ValueError("schema_version must be 2")
    for entry in entries:
        errors = validation_errors(entry, require_assessed=True)
        if errors:
            raise ValueError(entry["id"] + ": " + "; ".join(errors))
    assessments = Counter(e["acceleration"]["assessment"] for e in entries)
    roles = Counter(e["acceleration"]["ai_role"] for e in entries)
    distributions = Counter(e["distribution"]["status"] for e in entries)
    backends = [(e, b) for e in entries for b in e["acceleration"]["backends"]]
    lines = [
        "# Full-catalog acceleration matrix", "",
        "<!-- Generated by scripts/render-acceleration-matrix.py; edit the catalog, then regenerate. -->", "",
        "Source: [schema-2 catalog](../catalog/audio-104.json); identity/order checked against the "
        "[independent fixture](../tests/audio-catalog-identities.json). No network, Nix evaluation, "
        "model acquisition or hardware probing occurs during rendering.", "",
        f"**{len(entries)}** canonical repositories; **{assessments['complete']}** complete assessments; "
        f"**{assessments['blocked-evidence']}** blocked-evidence; **{assessments['pending']}** pending; "
        f"**{len(backends)}** backend records; **{distributions['packaged']}** packaged and "
        f"**{distributions['catalog-only']}** catalog-only repositories.", "",
        "AI roles (computed from the authoritative catalog, not inferred from product names): "
        + "; ".join(f"`{role}`: {count}" for role, count in sorted(roles.items())) + ".", "",
        "Backend records are component/platform/architecture/vendor/provider assessments, not delivered "
        "accelerated packages and not all neural inference. They also cover non-neural GPU DSP, "
        "unsupported routes and port work. Repository-level catalog-only counts must not be read as "
        "a count of neural plugins awaiting acceleration.", "",
        "Published package attributes and backend package attributes are separate. A `null` backend "
        "attribute does not publish a GPU alias, even when a private recipe override evaluated. "
        "Evaluation, linked build and shared-library load do not establish model execution, provider "
        "placement or host/audio acceptance. AMD hardware stages are policy-skipped. See "
        "[validation and limitations](acceleration-validation.md).", "",
        "## Canonical repository rows", "",
        "| ID | Repository | Assessment | AI role / execution | Distribution | Published package attribute | Build / runtime | Source note |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for entry in entries:
        a, d = entry["acceleration"], entry["distribution"]
        lines.append("| " + " | ".join([
            entry["id"], "`" + cell(entry["repository"]) + "`", a["assessment"],
            cell(a["ai_role"] + " / " + a["execution_mode"]), d["status"],
            attribute(d["nix_attribute"], local=d["status"] == "packaged"),
            cell(entry["verification"]["build"] + " / " + entry["verification"]["runtime"]),
            f"[source assessment](acceleration/{entry['id']}.md)",
        ]) + " |")
    lines += ["", "## Per-component backend stages", "",
              "Stage columns preserve catalog values in this order: evaluation / build / load and "
              "model_execution / provider_execution / host. `host` is hardware/host acceptance, "
              "not the model-free library-load stage.", "",
              "| ID / component | Platform / architecture | Vendor / provider | Upstream / integration | Backend package attribute | Evaluation / build / load | model_execution / provider_execution / host | CPU fallback |",
              "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for entry, backend in backends:
        v = backend["validation"]
        lines.append("| " + " | ".join([
            f"[{entry['id']}](acceleration/{entry['id']}.md) / {cell(backend['component'])}",
            cell(backend["platform"] + " / " + backend["architecture"]),
            cell(backend["vendor"] + " / " + backend["provider"]),
            cell(backend["upstream_status"] + " / " + backend["integration_status"]),
            attribute(backend["package_attribute"]),
            " / ".join(v[s] for s in ("evaluation", "build", "load")),
            " / ".join(v[s] for s in ("model_execution", "provider_execution", "host")),
            cell(backend["cpu_fallback"]),
        ]) + " |")
    lines += ["", "## Rights, evidence and next actions", "",
              "Rights metadata is informational and not a technical implementation gate. "
              "Consumers own use/distribution decisions; AI labels grant no copyright exemption. "
              "Models and drivers are user-owned: no automatic model downloads or driver activation "
              "are implied. Native packaging is independent of any custom Wine/installer framework.", ""]
    for entry in entries:
        a, rights = entry["acceleration"], entry["copyright"]
        lines += [f"### {entry['id']} — {cell(entry['repository'])}", "",
                  f"[Pinned source assessment](acceleration/{entry['id']}.md). "
                  f"License evidence: {cell(rights['license_evidence'])} "
                  f"Review: `{rights['review_status']}`; implementation gate: "
                  f"`{str(rights['implementation_gate']).lower()}`; consumer judgement required: "
                  f"`{str(rights['consumer_judgement_required']).lower()}`.", ""]
        if rights["concerns"]:
            lines += ["Concerns: " + cell("; ".join(rights["concerns"])), ""]
        if a["blocked_reason"]:
            lines += ["Blocked reason: " + cell(a["blocked_reason"]), ""]
        lines += ["Next action: " + cell(a["next_action"]), ""]
        lines += evidence_lines(a["evidence"])
        for b in a["backends"]:
            lines += ["", f"**{cell(b['component'])}: {cell(b['platform'])}/{cell(b['architecture'])}, "
                      f"{cell(b['vendor'])}/{cell(b['provider'])}**", "",
                      f"Source revision: {attribute(b['source_revision'])}; runtime ID: "
                      f"{attribute(b['runtime_id'])}. "
                      f"Validation reason: {cell(b['validation'].get('reason') or 'none recorded')}.", "",
                      "Next action: " + cell(b["next_action"]), ""]
            lines += evidence_lines(b["evidence"])
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=ROOT / "catalog/audio-104.json")
    parser.add_argument("--identities", type=Path, default=ROOT / "tests/audio-catalog-identities.json")
    parser.add_argument("--output", type=Path, default=ROOT / "docs/acceleration-matrix.md")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if missing/stale; never write")
    mode.add_argument("--write", action="store_true", help="write generated matrix (default)")
    args = parser.parse_args()
    try:
        content = render(json.loads(args.catalog.read_text(encoding="utf-8")),
                         json.loads(args.identities.read_text(encoding="utf-8"))).encode("utf-8")
        if args.check:
            if not args.output.exists() or args.output.read_bytes() != content:
                print(f"stale or missing matrix: {args.output}; run renderer --write", file=sys.stderr)
                return 1
            print("Acceleration matrix is fresh.")
        else:
            args.output.write_bytes(content)
            print(f"Wrote {args.output}")
        return 0
    except (OSError, ValueError, KeyError, TypeError) as error:
        print(f"Cannot render acceleration matrix: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
